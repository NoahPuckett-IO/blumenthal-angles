#!/usr/bin/env python3
"""Symmetry-reduced search for a 9-clique among the 528 strings at grid (22, 5).

Symmetries: rotation of the 44-cell circle and reflection. Both preserve validity and
compatibility. Orbits are indexed; for each orbit o we fix its representative v and look for
an 8-clique in P_o = N(v) ∩ {u : orbit(u) >= o}. A 9-clique has a member of minimal orbit o,
which after a symmetry is v itself. Counts B&B nodes for several vertex orderings.
"""
import itertools
import sys
import time

m, L, C = 22, 5, 3
M = 2 * m
FULL = (1 << M) - 1


def mk(s, pos):
    ch = set(pos) | {p + m for p in pos}
    x = 0
    v = s
    for i in range(M):
        if i in ch and i != 0:
            v = not v
        if v:
            x |= 1 << i
    return x


masks = set()
for pos in itertools.combinations(range(m), C):
    gaps = [pos[k + 1] - pos[k] for k in range(C - 1)] + [pos[0] + m - pos[-1]]
    if min(gaps) >= L:
        masks.add(mk(True, pos))
        masks.add(mk(False, pos))
masks = sorted(masks)
idx = {x: i for i, x in enumerate(masks)}
N = len(masks)


def rot(x, k):
    k %= M
    return ((x << k) | (x >> (M - k))) & FULL


def refl(x):
    return int(format(x, f"0{M}b"), 2)  # bit i -> bit M-1-i


def window(d):
    r = d
    for t in range(1, L):
        r &= rot(d, t)
    return r != 0


adj = [0] * N
for i in range(N):
    for j in range(i + 1, N):
        if window(masks[i] ^ masks[j]):
            adj[i] |= 1 << j
            adj[j] |= 1 << i

# orbits
orb = [-1] * N
reps = []
for i in range(N):
    if orb[i] >= 0:
        continue
    o = len(reps)
    reps.append(i)
    for k in range(M):
        for y in (rot(masks[i], k), rot(refl(masks[i]), k)):
            orb[idx[y]] = o
print("N", N, "orbits", len(reps), "sizes", [orb.count(o) for o in range(len(reps))])

nodes = 0


def colour_bound(P, order):
    # greedy colouring in the given order; returns per-vertex colour list
    res = []
    col = 0
    U = P
    while U:
        col += 1
        Q = U
        for v in order:
            if Q >> v & 1:
                res.append((v, col))
                Q &= ~adj[v]
                Q &= ~(1 << v)
                U &= ~(1 << v)
        # Q loop over order handles independence
    return res


def expand(P, k, order):
    """True iff no clique of size k in P."""
    global nodes
    nodes += 1
    if k <= 0:
        return False
    cb = colour_bound(P, order)
    for v, col in reversed(cb):
        if col < k:
            return True
        if not expand(P & adj[v], k - 1, order):
            return False
        P &= ~(1 << v)
    return True


for name, key in [("index", lambda v: v), ("degdesc", lambda v: -bin(adj[v]).count("1"))]:
    tot = 0
    t = time.time()
    for o, v in enumerate(reps):
        P = adj[v]
        for u in range(N):
            if P >> u & 1 and orb[u] < o:
                P &= ~(1 << u)
        nodes = 0
        verts = [u for u in range(N) if P >> u & 1]
        order = sorted(verts, key=key)
        ok = expand(P, 8, order)
        tot += nodes
        print(f"  {name} orbit {o}: |P|={len(verts)} no8={ok} nodes={nodes}", flush=True)
    print(name, "total nodes", tot, "time %.1fs" % (time.time() - t), flush=True)

# ---- export data for Lean: global relabel by degree desc ----
if "--export" in sys.argv:
    perm = sorted(range(N), key=lambda v: (-bin(adj[v]).count("1"), v))
    with open("GridData.lean", "w") as f:
        f.write("/-! Generated by sym_search.py: the 528 strings at (22,5), ordered by degree (desc). -/\n\n")
        f.write("def gridMasks : List Nat := [" + ", ".join(str(masks[v]) for v in perm) + "]\n\n")
        f.write("def gridOrbit : List Nat := [" + ", ".join(str(orb[v]) for v in perm) + "]\n\n")
        f.write("def gridReps : List Nat := [" + ", ".join(str(perm.index(r)) for r in reps) + "]\n")
    print("exported")
