"""Exact check of (R) for fixed (m, L) by SAT (docs/STEP5-NOTES.md, Attempt 3).

Same discretisation as relaxation.py. Asks whether a compatible family of size K exists:
variables x_f (f a valid sign function), clauses (-x_f | -x_g) for incompatible f, g, and a
cardinality constraint sum x_f >= K. UNSAT at K = 2^n + 1 verifies (R) at (m, L).

Symmetry breaking: the group generated by the shift s -> s[1:] + [1 - s[0]] (order 2m; shift by m is
global negation) and reflection acts on families. Every nonempty family can be moved so that it
contains the lexicographically smallest member of some fixed orbit; we split into one SAT call per
orbit O: "x_rep(O) = 1 and no member of an orbit earlier than O" (orbits ordered arbitrarily but
fixed). Each call is independent, so they run in parallel.

Usage: relaxation_sat.py m L K [workers]
Needs python-sat.
"""
import itertools
import sys
import time
from multiprocessing import Pool

from pysat.card import CardEnc, EncType
from pysat.formula import CNF
from pysat.solvers import Solver

from relaxation import compatible


def functions(m, L):
    """Same set as relaxation.functions, generated from sign-change positions (fast for large m).
    Oddness forces an odd number k of changes in [0, m); cyclic gaps (mod m) must all be >= L."""
    out = []
    for k in range(1, m // L + 1, 2):
        for c in itertools.combinations(range(m), k):
            if all(b - a >= L for a, b in zip(c, c[1:])) and c[0] + m - c[-1] >= L:
                for v0 in (0, 1):
                    s, v, cs = [], v0, set(c)
                    for i in range(m):
                        if i in cs and i > 0:
                            v ^= 1
                        s.append(v)
                    # position 0 is a change iff s[m-1] == s[0] (the wrap flips the value)
                    if (0 in cs) == (s[m - 1] == s[0]):
                        out.append(s)
    return sorted(out)


def orbit_reps(V):
    idx = {tuple(v): i for i, v in enumerate(V)}
    seen, orbits = set(), []
    for v in V:
        if tuple(v) in seen:
            continue
        orb, s = set(), list(v)
        for r in (s, s[::-1]):
            t = list(r)
            for _ in range(2 * len(t)):
                orb.add(tuple(t))
                t = t[1:] + [1 - t[0]]
        seen |= orb
        orbits.append(sorted(idx[o] for o in orb))
    return orbits


def setup(m, L, K):
    V = functions(m, L)
    N = len(V)
    cnf = CNF()
    for i, j in itertools.combinations(range(N), 2):
        if not compatible(V[i], V[j], L):
            cnf.append([-(i + 1), -(j + 1)])
    # Partition V greedily into classes of pairwise incompatible functions; a family meets each class
    # at most once, so the cardinality constraint can count classes y_c = OR(x_f : f in c) instead.
    inc = [[not compatible(V[i], V[j], L) or i == j for j in range(N)] for i in range(N)]
    left, classes = set(range(N)), []
    while left:
        c = []
        for i in sorted(left, key=lambda i: -sum(inc[i][j] for j in left)):
            if all(inc[i][j] for j in c):
                c.append(i)
        classes.append(c)
        left -= set(c)
    ys = []
    for k, c in enumerate(classes):
        y = N + 1 + k
        ys.append(y)
        cnf.append([-y] + [i + 1 for i in c])
    card = CardEnc.atleast(lits=ys, bound=K, top_id=N + len(classes), encoding=EncType.totalizer)
    cnf.extend(card.clauses)
    return V, cnf, orbit_reps(V)


def orbit_cubes(V, L, orbit, rep):
    """All compatible subsets of `orbit` that contain `rep`, as full assignments of the orbit's variables."""
    rest = [i for i in orbit if i != rep]
    out = []

    def dfs(pos, chosen):
        if pos == len(rest):
            out.append([(i + 1) if i in chosen else -(i + 1) for i in orbit])
            return
        i = rest[pos]
        if all(compatible(V[i], V[j], L) for j in chosen):
            dfs(pos + 1, chosen | {i})
        dfs(pos + 1, chosen)

    dfs(0, {rep})
    return out


_cache = {}


def solve_case(args):
    m, L, K, k, cube = args
    if (m, L, K) not in _cache:
        _cache.clear()
        _cache[m, L, K] = setup(m, L, K)
    V, cnf, orbits = _cache[m, L, K]
    assume = [orbits[k][0] + 1] + [-(i + 1) for o in orbits[:k] for i in o] + list(cube)
    t = time.time()
    with Solver(name="cadical195", bootstrap_with=cnf.clauses) as s:  # fresh solver: no learnt-clause carry-over
        sat = s.solve(assumptions=assume)
        model = s.get_model() if sat else None
    fam = None
    if sat:
        fam = ["".join(map(str, V[i])) for i in range(len(V)) if model[i] > 0]
    return k, sat, time.time() - t, fam


if __name__ == "__main__":
    m, L, K = map(int, sys.argv[1:4])
    W = int(sys.argv[4]) if len(sys.argv) > 4 else 14
    t0 = time.time()
    V, cnf, orbits = setup(m, L, K)
    print(f"m={m} L={L} L/m={L/m:.4f} K={K} functions={len(V)} orbits={len(orbits)} clauses={len(cnf.clauses)}", flush=True)
    # Case 0 has no exclusions and is the hard one; cube it on the exact set of orbit-0 members.
    cubes = orbit_cubes(V, L, orbits[0], orbits[0][0])
    print(f"case 0 split into {len(cubes)} cubes", flush=True)
    jobs = [(m, L, K, 0, c) for c in cubes] + [(m, L, K, k, ()) for k in range(1, len(orbits))]
    found, done = None, 0
    with Pool(W) as p:
        for k, sat, dt, fam in p.imap_unordered(solve_case, jobs, chunksize=4):
            done += 1
            if sat or dt > 10 or done % 50 == 0:
                print(f"  [{done}/{len(jobs)}] case {k}: {'SAT' if sat else 'UNSAT'} {dt:.1f}s", flush=True)
            if sat:
                found = fam
                p.terminate()
                break
    if found:
        print("FAMILY of size", len(found), ":", " ".join(found))
    else:
        print(f"UNSAT: no compatible family of size {K}")
    print(f"total {time.time() - t0:.1f}s")
